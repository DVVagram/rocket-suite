"""Flight simulation: RocketPy, driven by RocketSerializer's own construction.

The RocketPy objects are built by executing the code RocketSerializer's
`NotebookBuilder` generates for the converted design, so the suite never keeps a
second, drifting mapping from parameters to RocketPy classes.  All physics is
RocketPy's; nothing is integrated here.
"""

from __future__ import annotations

import json
import math
import os
from pathlib import Path

from . import convert

# Cells that only exist to render the notebook are skipped; the `.info()`
# calls open a figure per channel, which matters on a small machine.
_SKIP_PREFIXES = ("plt.", "flight.all_info", "flight.info", "%", "display(", "fig.")
_SKIP_CONTAINS = (".all_info(", ".info(", "plt.show(")


def _numeric_series(fn, times) -> list[float] | None:
    if fn is None:
        return None
    out: list[float] = []
    try:
        for t in times:
            value = float(fn(t))
            out.append(value if math.isfinite(value) else 0.0)
    except Exception:
        return None
    return out


def _time_of_event(flight, name: str) -> float | None:
    try:
        value = getattr(flight, name)
    except Exception:
        return None
    try:
        return float(value)
    except Exception:
        return None


def run(ork_path: Path, out_dir: Path, settings: dict | None = None) -> dict:
    """Convert a design and fly it. Returns parameters, report and flight data."""
    settings = settings or {}
    converted = convert.convert(ork_path, out_dir)
    params = converted["parameters"]
    params_path = converted["params_path"]

    if settings.get("environment"):
        params["environment"].update(settings["environment"])
        params_path.write_text(json.dumps(params, indent=4, sort_keys=True), encoding="utf-8")

    nb_path = convert.build_notebook(params_path, out_dir)
    notebook = json.loads(nb_path.read_text(encoding="utf-8"))

    lines: list[str] = []
    for cell in notebook.get("cells", []):
        if cell.get("cell_type") != "code":
            continue
        source = "".join(cell.get("source", []))
        for line in source.splitlines():
            stripped = line.strip()
            if stripped.startswith(_SKIP_PREFIXES):
                continue
            if any(token in stripped for token in _SKIP_CONTAINS):
                continue
            lines.append(line)
        lines.append("")

    os.environ.setdefault("MPLBACKEND", "Agg")
    namespace: dict = {"__name__": "__rocketpy_flight__"}
    code = compile("\n".join(lines), str(nb_path), "exec")

    # RocketSerializer's notebook refers to the generated CSVs by paths relative
    # to its output folder, so the generated code runs with that folder as cwd.
    previous_cwd = os.getcwd()
    os.chdir(out_dir)
    try:
        exec(code, namespace)  # noqa: S102 - code generated by RocketSerializer
    finally:
        os.chdir(previous_cwd)

    flight = namespace.get("flight")
    rocket = namespace.get("rocket")
    if flight is None:
        raise RuntimeError("RocketSerializer's notebook did not produce a RocketPy flight")

    t_final = float(getattr(flight, "t_final", 0.0) or 0.0)
    steps = 220
    times = [t_final * i / (steps - 1) for i in range(steps)] if t_final > 0 else [0.0]

    series = {
        "time": times,
        "altitude": _numeric_series(getattr(flight, "z", None), times),
        "vertical_velocity": _numeric_series(getattr(flight, "vz", None), times),
        "speed": _numeric_series(getattr(flight, "speed", None), times),
        "acceleration": _numeric_series(getattr(flight, "acceleration", None), times),
        "mach": _numeric_series(getattr(flight, "MachNumber", None), times),
        "mass": _numeric_series(getattr(flight, "mass", None), times),
        "thrust": _numeric_series(getattr(flight, "thrust", None), times),
        "drag": _numeric_series(getattr(flight, "drag", None), times),
        "downrange": _numeric_series(getattr(flight, "x", None), times),
        "crossrange": _numeric_series(getattr(flight, "y", None), times),
    }
    # Rocket position along the flight path is what the 3-D viewer animates.
    if series["downrange"] is None:
        series["downrange"] = [0.0] * len(times)

    events = []
    for label, attribute in (
        ("Rail exit", "out_of_rail_time"),
        ("Motor burnout", "burn_out_time"),
        ("Apogee", "apogee_time"),
        ("Impact", "t_final"),
    ):
        t = _time_of_event(flight, attribute)
        if t is None and rocket is not None:
            motor = getattr(rocket, "motor", None)
            if label == "Motor burnout" and motor is not None:
                t = _time_of_event(motor, attribute)
        if t is not None and t > 0:
            altitude = None
            try:
                altitude = float(flight.z(t))
            except Exception:
                pass
            events.append({"name": label, "time": t, "altitude": altitude})

    def _safe(attr: str) -> float | None:
        try:
            value = getattr(flight, attr)
            return float(value)
        except Exception:
            return None

    summary = {
        "apogee": _safe("apogee"),
        "apogee_time": _safe("apogee_time"),
        "max_speed": _safe("max_speed"),
        "max_mach": _safe("max_mach_number"),
        "max_acceleration": _safe("max_acceleration"),
        "rail_velocity": _safe("out_of_rail_velocity"),
        "flight_time": t_final,
        "apogee_x": _safe("apogee_x"),
        "apogee_y": _safe("apogee_y"),
    }

    reference = (params.get("stored_results") or {})
    comparison = {}
    for ours, theirs, label in (
        ("apogee", "max_altitude", "Apogee (m)"),
        ("max_speed", "max_velocity", "Max velocity (m/s)"),
        ("max_mach", "max_mach", "Max Mach"),
    ):
        a, b = summary.get(ours), reference.get(theirs)
        if a is not None and b:
            comparison[label] = {
                "rocketpy": a,
                "openrocket": b,
                "delta_percent": round((a - b) / b * 100, 1),
            }

    return {
        "summary": summary,
        "events": events,
        "series": series,
        "comparison": comparison,
        "report": converted["report"],
        "parameters": params,
        "engine": {
            "flight": "RocketPy",
            "conversion": "RocketSerializer",
            "design": "OpenRocket",
        },
    }
